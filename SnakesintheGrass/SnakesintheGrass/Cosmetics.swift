        Skin(id: "ghost", name: "ghost", tier: .premium, previewColor: UIColor(white: 0.9, alpha: 0.6)),
        Skin(id: "indigo", name: "indigo", tier: .premium, previewColor: UIColor(red: 0.345, green: 0.337, blue: 0.839, alpha: 1)),
    ]

    /// Skins shown in the customize screen right now: in-window, or already owned.
    static func visible(owned: (Skin) -> Bool, at date: Date = Date()) -> [Skin] {
        let list = all.filter { $0.isAvailable(at: date) || owned($0) }
        return SkinCategory.allCases.flatMap { c in list.filter { $0.category == c } }
    }

    /// Unknown or removed ids (e.g. the dropped "signal") return nil; callers fall back to og.
    static func skin(id: String?) -> Skin? { all.first { $0.id == id } }

    static func date(_ ymd: String) -> Date? {
        let f = DateFormatter(); f.dateFormat = "yyyy-MM-dd"; f.timeZone = TimeZone(identifier: "UTC")
        return f.date(from: ymd)
    }
}

// MARK: - Maps

struct GameMap: Identifiable, Equatable {
    enum Edges: Equatable {
        case wrap   // classic: leave one side, enter the other
        case kill   // touching the edge ends the run
    }

    let id: String
    let name: String
    let tier: CosmeticTier
    /// Fill behind the board area. Black keeps the original look.
    let background: UIColor
    /// Optional second color drawn as a checker (grass pattern). nil = flat.
    let checker: UIColor?
    let obstacleColor: UIColor
    let obstacles: Set<GridCell>
    let edges: Edges
    /// Optional seasonal window (same idea as skins). nil = always listed.
    var availableFrom: Date? = nil
    var availableUntil: Date? = nil

    /// True when the score is not directly comparable with the classic board.
    var changesDifficulty: Bool { !obstacles.isEmpty || edges == .kill }

    func isAvailable(at date: Date = Date()) -> Bool {
        if let f = availableFrom, date < f { return false }
        if let u = availableUntil, date > u { return false }
        return true
    }
}

