    static var assetExists: [String: Bool] = [:]

    /// The 14 piece names every skin provides (skin_<id>_<piece>).
    static let pieces = ["head_up", "head_down", "head_left", "head_right",
                         "body_horizontal", "body_vertical", "body_topleft", "body_topright",
                         "body_bottomleft", "body_bottomright",
