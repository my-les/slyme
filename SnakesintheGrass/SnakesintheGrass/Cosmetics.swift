enum CosmeticTier: String, Codable {
    case free
    case premium
}

/// A grid cell on the fixed 18x32 board.
struct GridCell: Hashable, Codable {
    let x: Int
    let y: Int
    init(_ x: Int, _ y: Int) { self.x = x; self.y = y }
}

// MARK: - Skins

/// Grouping in the customize screen. Add cases freely.
enum SkinCategory: String, CaseIterable {
    case core, seasonal, branded, textured
}

/// Where a skin's 14 piece images come from. Rendering is identical either way:
/// both load `skin_<id>_<piece>` from Assets.xcassets (og uses the bare piece names).
enum SkinArt: Equatable {
    /// Recolor of the og art, generated by tools/recolor_skins.py from tools/skins.json.
    case recolor
    /// Hand-made texture set dropped into the asset catalog (see docs/ADDING_SKINS.md).
    case textured
}

struct Skin: Identifiable, Equatable {
    let id: String
    let name: String
    let tier: CosmeticTier
    /// Card accent only.
    let previewColor: UIColor
    var category: SkinCategory = .core
    var art: SkinArt = .recolor
    /// Optional availability window (seasonal). nil = open-ended.
    var availableFrom: Date? = nil
    var availableUntil: Date? = nil

    func isAvailable(at date: Date = Date()) -> Bool {
        if let f = availableFrom, date < f { return false }
        if let u = availableUntil, date > u { return false }
        return true
    }

    /// Asset name for an og piece name like "head_up". Falls back to the og
    /// piece if a skin image is missing, so a half-finished set never crashes.
    func textureName(for piece: String) -> String {
        if id == SkinCatalog.defaultID { return piece }
        let name = "skin_\(id)_\(piece)"
        if let hit = SkinCatalog.assetExists[name] { return hit ? name : piece }
        let ok = UIImage(named: name) != nil
        SkinCatalog.assetExists[name] = ok
        return ok ? name : piece
    }

    /// Build one segment node for this skin.
    func makeSegment(textureName piece: String, isHead: Bool, size: CGSize) -> SKSpriteNode {
        SKSpriteNode(texture: SKTexture(imageNamed: textureName(for: piece)), size: size)
    }
}

enum SkinCatalog {
    static let defaultID = "og"
